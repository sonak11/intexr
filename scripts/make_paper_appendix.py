#!/usr/bin/env python3
"""Generate paper appendix files from the code and data, so the paper never drifts from what was run.

  python3 scripts/make_paper_appendix.py      # -> paper1/generated/prompts.tex, paper1/generated/example.tex
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from intexr import data, gate, prompts, scope  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "paper1", "generated")
EXAMPLE_CASE = "ms-val-99"  # measles vs. rubella: depth-2 chain; authority-only becomes U; has a conflicting variant
SHOW = ("valid", "false", "authority", "conflicting")

LATEX_SPECIAL = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
                 "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def tex(s):
    return "".join(LATEX_SPECIAL.get(ch, ch) for ch in s).replace("→", r"$\rightarrow$").replace("≥", r"$\geq$")


def listing(title, text):
    return (f"\\medskip\\noindent\\textbf{{{tex(title)}}}\\nopagebreak\n\\begin{{lstlisting}}\n{text.strip()}\n\\end{{lstlisting}}\n")


def prompts_tex():
    dialogue_sys, dialogue_msgs = prompts.dialogue_messages({
        "context": "<TASK>", "prior_evidence": [{"id": "e1", "text": "<PRIOR EVIDENCE>"}],
        "original_response": "<ORIGINAL RESPONSE>", "feedback": {"speaker_role": "<ROLE>", "text": "<FEEDBACK>"},
        "new_evidence": [{"id": "n1", "text": "<NEW EVIDENCE>"}]})
    dialogue = "\n\n".join(f"[{m['role']}]\n{m['content']}" for m in dialogue_msgs)
    parts = [
        "% generated by scripts/make_paper_appendix.py from intexr/prompts.py, intexr/scope.py, intexr/gate.py\n",
        "All prompts are used verbatim at temperature 0. User messages give the task, the evidence with identifiers "
        "and provenance, the original response (with numbered claims for structured systems), and the feedback.\n",
        listing("Dialogue (no system prompt; three turns)", dialogue),
        listing("Evidence-aware prompt (system)", prompts.EVIDENCE_SYS),
        listing("Always rewrite (system)", prompts.REWRITE_SYS),
        listing("Single-prompt scope-first (system)", prompts.SCOPE_SYS),
        listing("Verify-then-revise baseline, step 1: verify (system)", prompts.VERIFY_SYS),
        listing("Verify-then-revise baseline, step 2: revise (system)", prompts.VERIFIED_REVISE_SYS),
        listing("Scope-first pipeline, step 1: align (system)", scope.ALIGN_SYS),
        listing("Scope-first pipeline, step 3: revise (system)", scope.REVISE_SYS),
        listing("Evidence gate, LLM scorer (system)", gate.NLI_SYS),
        listing("Claim-alignment judge (system)", prompts.JUDGE_SYS),
    ]
    return "\n".join(parts)


def example_tex(exs):
    case = [e for e in exs if e["source"].get("medec_id") == EXAMPLE_CASE]
    by = {e["id"].rsplit("-", 1)[1]: e for e in case}
    base = by["valid"]
    lines = ["% generated by scripts/make_paper_appendix.py from paperB/data/medec_scope_v0.json\n",
             f"\\paragraph{{Source.}} MEDEC note {tex(EXAMPLE_CASE)} (CC BY 4.0), with the error sentence removed, "
             "is the prior evidence $e_1$. The original response and all other text below were authored for "
             "\\ms{} (LLM-assisted, not yet clinically reviewed).\n",
             "\\paragraph{Original response, decomposed into claims.}\n\\begin{itemize}\\itemsep0pt"]
    for c in base["claims"]:
        lines.append(f"  \\item[{c['id']}] {tex(c['text'])}")
    deps = ", ".join(f"{a}$\\rightarrow${b}" for a, b in base["gold"]["dependencies"])
    lines += ["\\end{itemize}", f"Gold dependencies: {deps}.\n",
              f"\\paragraph{{New evidence $n_1$.}} {tex(base['new_evidence'][0]['text'])}\n"]
    for var in SHOW:
        ex = by[var]
        g = ex["gold"]
        extra = [e for e in ex["new_evidence"] if e["id"] != "n1"]
        lines.append(f"\\paragraph{{Condition: {var}.}} Feedback ({tex(ex['feedback']['speaker_role'].replace('_', ' '))}): "
                     f"``{tex(ex['feedback']['text'])}''" + ("" if ex["new_evidence"] else " \\emph{No new evidence.}"))
        for e in extra:
            lines.append(f" Additional evidence ${e['id'][0]}_{e['id'][1:]}$: {tex(e['text'])}")
        labs = ", ".join(f"{cid}\\,{v['label']}" + (f"$^{{{v['trigger'][0]}}}$" if v["label"] == "U" else "")
                         + ("$^{+}$" if v.get("support") == "supported" else "") for cid, v in g["claims"].items())
        lines.append(f"\\\\ Gold labels: {labs}; verdict \\emph{{{g['feedback_verdict']}}}.\n")
        if var == "valid":
            lines.append(f"Target revision: {tex(g['target_revision'])}\n")
    lines.append("$^{+}$ supported by evidence; U$^{f}$ / U$^{d}$ / U$^{e}$: unresolved by feedback / dependency / conflicting evidence.\n")
    return "\n".join(lines)


def main():
    os.makedirs(OUT, exist_ok=True)
    exs = data.load(os.path.join(os.path.dirname(__file__), "..", "paperB", "data", "medec_scope_v0.json"))
    with open(os.path.join(OUT, "prompts.tex"), "w") as f:
        f.write(prompts_tex())
    with open(os.path.join(OUT, "example.tex"), "w") as f:
        f.write(example_tex(exs))
    print("wrote paper1/generated/prompts.tex and paper1/generated/example.tex")


if __name__ == "__main__":
    main()
